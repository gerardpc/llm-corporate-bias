def combination_exists(
    model_id: str,
    run: int,
    now_value: float,
    later_value: float,
    delay_years: int,
    temperature: float,
) -> bool:
    """
    Check if a specific combination already exists in the temporal_discounting table.

    Args:
        model_id: The model identifier
        run: The run number
        now_value: The immediate value
        later_value: The delayed value
        delay_years: The delay in years
        temperature: The temperature setting

    Returns:
        True if the combination exists, False otherwise
    """
    query = f"""
        SELECT COUNT(*) as count
        FROM {FULL_TABLE_NAME}
        WHERE model_id = %s
        AND run = %s
        AND now_value = %s
        AND later_value = %s
        AND delay_years = %s
        AND temperature = %s
    """

    result_df = query_db(
        query,
        (model_id, run, now_value, later_value, delay_years, temperature),
    )
    result = result_df.to_dict("records")
    return result[0]["count"] > 0 if result else False


def get_existing_combination(
    model_id: str,
    run: int,
    now_value: float,
    later_value: float,
    delay_years: int,
    temperature: float,
) -> Optional[dict]:
    """
    Retrieve an existing combination from the temporal_discounting table.

    Args:
        model_id: The model identifier
        run: The run number
        now_value: The immediate value
        later_value: The delayed value
        delay_years: The delay in years
        temperature: The temperature setting

    Returns:
        Dictionary with the existing combination data, or None if not found
    """
    query = f"""
        SELECT preference, answer, question, full_prompt, reasoning_tokens
        FROM {FULL_TABLE_NAME}
        WHERE model_id = %s
        AND run = %s
        AND now_value = %s
        AND later_value = %s
        AND delay_years = %s
        AND temperature = %s
        LIMIT 1
    """

    result_df = query_db(
        query,
        (model_id, run, now_value, later_value, delay_years, temperature),
    )
    result = result_df.to_dict("records")

    if result:
        row = result[0]
        return {
            "preference": row["preference"],
            "answer": row["answer"],
            "question": row["question"],
            "full_prompt": row["full_prompt"],
            "reasoning_tokens": row["reasoning_tokens"],
        }

    return None


def select_all_temporal_discounting() -> pd.DataFrame:
    """
    Retrieve all rows from the temporal_discounting table.

    Returns:
        pd.DataFrame: DataFrame containing all temporal discounting experiment data
    """
    query = f"""
        SELECT
            id,
            run,
            now_value,
            later_value,
            delay_years,
            preference,
            full_prompt,
            question,
            option_A,
            option_B,
            answer,
            model_id,
            reasoning_model,
            reasoning_tokens,
            temperature,
            created_at
        FROM {FULL_TABLE_NAME}
        ORDER BY created_at ASC
    """

    return query_db(query)


