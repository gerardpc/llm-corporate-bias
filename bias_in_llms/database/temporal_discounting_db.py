def insert_temporal_discounting_row(
    model_id: str,
    run: int,
    now_value: float,
    later_value: float,
    delay_years: int,
    preference: str,
    full_prompt: str,
    question: str,
    option_A: str,
    option_B: str,
    answer: str,
    reasoning_model: bool,
    reasoning_tokens: int,
    temperature: float,
    debug: bool = False,
) -> None:
    """
    Insert a row into the temporal_discounting table.

    Args:
        model_id: The model identifier
        run: The run number
        now_value: The immediate value
        later_value: The delayed value
        delay_years: The delay in years
        preference: The preference result
        full_prompt: The full prompt text
        question: The question text
        option_A: The text for option A
        option_B: The text for option B
        answer: The answer choice
        reasoning_model: Whether reasoning model was used
        reasoning_tokens: Number of reasoning tokens
        temperature: The temperature setting
        debug: Flag to enable debug output
    """
    query = f"""
        INSERT INTO {FULL_TABLE_NAME} (
            model_id, run, now_value, later_value, delay_years, preference,
            full_prompt, question, option_A, option_B, answer,
            reasoning_model, reasoning_tokens, temperature
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
    """

    params = (
        model_id,
        run,
        now_value,
        later_value,
        delay_years,
        preference,
        full_prompt,
        question,
        option_A,
        option_B,
        answer,
        reasoning_model,
        reasoning_tokens,
        temperature,
    )

    execute_query(query, params)

    if debug:
        print("Temporal-discounting row inserted into PostgreSQL.")
