"""
Database utilities specifically for the *temporal-discounting* experiment.

The goal is to keep each experiment's persistence logic neatly scoped so that
schema changes cannot accidentally break unrelated experiments.

Now uses PostgreSQL instead of SQLite.
"""

import logging
from typing import Optional

import pandas as pd

from bias_in_llms.database.database import (
    execute_query,
    query_db,
    sync_id_sequence,
)

# Constants
TABLE_SCHEMA = "bias_in_llms"
TABLE_NAME = "temporal_discounting"
FULL_TABLE_NAME = f"{TABLE_SCHEMA}.{TABLE_NAME}"

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Table initialisation
# ---------------------------------------------------------------------------


def initialize_temporal_discounting_db() -> None:  # noqa: D401
    """Initialise the PostgreSQL table for the *temporal-discounting* experiment."""
    execute_query(f"CREATE SCHEMA IF NOT EXISTS {TABLE_SCHEMA}")

    # Check if table exists
    table_exists_query = """
        SELECT EXISTS (
            SELECT 1 FROM information_schema.tables
            WHERE table_schema = %s
            AND table_name = %s
        ) AS exists;
    """

    result_df = query_db(
        table_exists_query,
        (TABLE_SCHEMA, TABLE_NAME),
    )
    result = result_df.to_dict("records")

    if not result[0]["exists"]:
        create_table_query = f"""
            CREATE TABLE {FULL_TABLE_NAME} (
                id SERIAL PRIMARY KEY,
                run INTEGER NOT NULL,
                now_value REAL,
                later_value REAL,
                delay_years INTEGER,
                preference TEXT,
                full_prompt TEXT,
                question TEXT,
                option_A TEXT,
                option_B TEXT,
                answer TEXT,
                model_id TEXT,
                reasoning_model BOOLEAN,
                reasoning_tokens INTEGER,
                temperature REAL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
        """
        execute_query(create_table_query)
        print(f"Table {FULL_TABLE_NAME} created successfully")
    else:
        print(f"Table {FULL_TABLE_NAME} already exists")

        # Check if id column has identity (auto-increment)
        identity_check_query = """
            SELECT is_identity
            FROM information_schema.columns
            WHERE table_schema = %s
            AND table_name = %s
            AND column_name = %s
        """

        identity_result_df = query_db(
            identity_check_query,
            (TABLE_SCHEMA, TABLE_NAME, "id"),
        )
        identity_result = identity_result_df.to_dict("records")

        if identity_result and identity_result[0]["is_identity"] == "NO":
            print("Adding identity to id column...")
            fix_identity_query = f"""
                ALTER TABLE {FULL_TABLE_NAME}
                ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY
            """
            execute_query(fix_identity_query)
            print("Identity added to id column successfully")

        # Synchronize sequence to start from 1 if table is empty,
        # or continue from max(id)
        print("Synchronizing ID sequence...")
        sync_id_sequence(FULL_TABLE_NAME)


